const DIET = { V: 'veg', N: 'non_veg', E: 'egg' };

/** One catalogue row per dish and per printed price choice, in board order. */
export function menuRows() {
  const rows = [];
  for (const s of SECTIONS) {
    for (const [name, price, diet, description, photo] of s.items) {
      const base = { category: s.category, station: s.station, dietary: DIET[diet], description, photo_query: photo, photo_key: name };
      if (typeof price === 'number') rows.push({ ...base, name, price });
      else for (const [choice, amount] of Object.entries(price)) rows.push({ ...base, name: `${name} (${choice})`, price: amount });
    }
  }
  return rows;
}
